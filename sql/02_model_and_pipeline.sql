-- 02: Star schema, engineered features, scheduled pipeline (Evening 2)
-- Full table names are used so the scheduled task runs without worksheet context.
USE ROLE ACCOUNTADMIN; USE WAREHOUSE HR_WH; USE SCHEMA HR_ANALYTICS.ANALYTICS;

CREATE OR REPLACE PROCEDURE HR_ANALYTICS.ANALYTICS.REFRESH_MODEL()
RETURNS STRING
LANGUAGE SQL
AS
$$
BEGIN
  -- Department dimension
  CREATE OR REPLACE TABLE HR_ANALYTICS.ANALYTICS.DIM_DEPARTMENT AS
  SELECT ROW_NUMBER() OVER (ORDER BY DEPARTMENT) AS DEPARTMENT_ID, DEPARTMENT
  FROM (SELECT DISTINCT DEPARTMENT FROM HR_ANALYTICS.RAW.EMPLOYEES);

  -- Employee dimension (descriptive attributes)
  CREATE OR REPLACE TABLE HR_ANALYTICS.ANALYTICS.DIM_EMPLOYEE AS
  SELECT EMPLOYEE_NUMBER, AGE, GENDER, MARITAL_STATUS, EDUCATION, EDUCATION_FIELD,
         JOB_ROLE, JOB_LEVEL, BUSINESS_TRAVEL, DISTANCE_FROM_HOME
  FROM HR_ANALYTICS.RAW.EMPLOYEES;

  -- Attrition features (a view, so the fact table can be refreshed in place and keep its masking policy)
  CREATE OR REPLACE VIEW HR_ANALYTICS.ANALYTICS.V_ATTRITION_FEATURES AS
  SELECT e.EMPLOYEE_NUMBER,
         d.DEPARTMENT_ID,
         e.DEPARTMENT,
         e.JOB_ROLE,
         IFF(e.ATTRITION = 'Yes', 1, 0)                      AS ATTRITION_FLAG,
         IFF(e.OVER_TIME = 'Yes', 1, 0)                      AS OVERTIME_FLAG,
         CASE WHEN e.YEARS_AT_COMPANY <= 1 THEN '0-1 years'
              WHEN e.YEARS_AT_COMPANY <= 4 THEN '2-4 years'
              WHEN e.YEARS_AT_COMPANY <= 9 THEN '5-9 years'
              ELSE '10+ years' END                          AS TENURE_BAND,
         e.MONTHLY_INCOME,
         e.JOB_SATISFACTION,
         e.ENVIRONMENT_SATISFACTION,
         e.WORK_LIFE_BALANCE,
         ROUND((e.JOB_SATISFACTION + e.ENVIRONMENT_SATISFACTION + e.WORK_LIFE_BALANCE) / 3, 2)
                                                             AS SATISFACTION_SCORE,
         e.YEARS_SINCE_LAST_PROMOTION,
         IFF(e.YEARS_SINCE_LAST_PROMOTION >= 5, 1, 0)        AS STALLED_PROMOTION_FLAG,
         e.DISTANCE_FROM_HOME
  FROM HR_ANALYTICS.RAW.EMPLOYEES e
  JOIN HR_ANALYTICS.ANALYTICS.DIM_DEPARTMENT d ON d.DEPARTMENT = e.DEPARTMENT;

  -- Fact table: created once, then overwritten in place on every refresh
  CREATE TABLE IF NOT EXISTS HR_ANALYTICS.ANALYTICS.FACT_ATTRITION AS
    SELECT * FROM HR_ANALYTICS.ANALYTICS.V_ATTRITION_FEATURES WHERE 1 = 0;
  INSERT OVERWRITE INTO HR_ANALYTICS.ANALYTICS.FACT_ATTRITION
    SELECT * FROM HR_ANALYTICS.ANALYTICS.V_ATTRITION_FEATURES;

  RETURN 'Model refreshed';
END;
$$;

CALL HR_ANALYTICS.ANALYTICS.REFRESH_MODEL();

-- Schedule it as a daily batch pipeline (6 am Pacific)
CREATE OR REPLACE TASK HR_ANALYTICS.ANALYTICS.REFRESH_MODEL_DAILY
  WAREHOUSE = HR_WH
  SCHEDULE = 'USING CRON 0 6 * * * America/Los_Angeles'
AS CALL HR_ANALYTICS.ANALYTICS.REFRESH_MODEL();
ALTER TASK HR_ANALYTICS.ANALYTICS.REFRESH_MODEL_DAILY RESUME;
-- To save trial credits later: ALTER TASK HR_ANALYTICS.ANALYTICS.REFRESH_MODEL_DAILY SUSPEND;

-- Quick check: attrition rate by department
SELECT DEPARTMENT, COUNT(*) AS EMPLOYEES, ROUND(100 * AVG(ATTRITION_FLAG), 1) AS ATTRITION_PCT
FROM HR_ANALYTICS.ANALYTICS.FACT_ATTRITION GROUP BY DEPARTMENT ORDER BY ATTRITION_PCT DESC;
