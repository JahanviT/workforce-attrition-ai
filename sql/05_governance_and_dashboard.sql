-- 05: PII masking + dashboard queries (Weekend, day 1)
USE ROLE ACCOUNTADMIN; USE WAREHOUSE HR_WH; USE SCHEMA HR_ANALYTICS.ANALYTICS;

-- Mask employee IDs for everyone except admins (Enterprise edition feature)
CREATE OR REPLACE MASKING POLICY ANALYTICS.MASK_EMPLOYEE_ID AS (VAL NUMBER) RETURNS NUMBER ->
  CASE WHEN CURRENT_ROLE() IN ('ACCOUNTADMIN', 'HR_ADMIN') THEN VAL ELSE NULL END;

ALTER TABLE ANALYTICS.FACT_ATTRITION
  MODIFY COLUMN EMPLOYEE_NUMBER SET MASKING POLICY ANALYTICS.MASK_EMPLOYEE_ID;

-- Test it with a read-only analyst role
CREATE ROLE IF NOT EXISTS HR_ANALYST;
GRANT USAGE ON WAREHOUSE HR_WH TO ROLE HR_ANALYST;
GRANT USAGE ON DATABASE HR_ANALYTICS TO ROLE HR_ANALYST;
GRANT USAGE ON SCHEMA HR_ANALYTICS.ANALYTICS TO ROLE HR_ANALYST;
GRANT SELECT ON ALL TABLES IN SCHEMA HR_ANALYTICS.ANALYTICS TO ROLE HR_ANALYST;
SET MY_USER = CURRENT_USER();
GRANT ROLE HR_ANALYST TO USER IDENTIFIER($MY_USER);

USE ROLE HR_ANALYST;
SELECT EMPLOYEE_NUMBER, DEPARTMENT, ATTRITION_FLAG FROM ANALYTICS.FACT_ATTRITION LIMIT 5;  -- IDs show as NULL
USE ROLE ACCOUNTADMIN;

-- Dashboard queries (Snowsight dashboard tiles or export to Tableau Public)
-- Tile 1: attrition by department
SELECT DEPARTMENT, ROUND(100 * AVG(ATTRITION_FLAG), 1) AS ATTRITION_PCT
FROM ANALYTICS.FACT_ATTRITION GROUP BY DEPARTMENT ORDER BY ATTRITION_PCT DESC;

-- Tile 2: overtime vs. no overtime
SELECT IFF(OVERTIME_FLAG = 1, 'Overtime', 'No overtime') AS GROUP_NAME,
       ROUND(100 * AVG(ATTRITION_FLAG), 1) AS ATTRITION_PCT
FROM ANALYTICS.FACT_ATTRITION GROUP BY 1;

-- Tile 3: attrition by job role
SELECT JOB_ROLE, COUNT(*) AS EMPLOYEES, ROUND(100 * AVG(ATTRITION_FLAG), 1) AS ATTRITION_PCT
FROM ANALYTICS.FACT_ATTRITION GROUP BY JOB_ROLE ORDER BY ATTRITION_PCT DESC;

-- Tile 4: attrition by tenure band
SELECT TENURE_BAND, ROUND(100 * AVG(ATTRITION_FLAG), 1) AS ATTRITION_PCT
FROM ANALYTICS.FACT_ATTRITION GROUP BY TENURE_BAND ORDER BY ATTRITION_PCT DESC;

-- Tile 5: exit comment themes
SELECT PRIMARY_THEME, COUNT(*) AS COMMENTS
FROM ANALYTICS.EXIT_COMMENT_EMBEDDINGS GROUP BY PRIMARY_THEME ORDER BY COMMENTS DESC;
