-- 03: Embeddings (Evening 2)
-- Note: new and trial accounts must use AI_EMBED (legacy SNOWFLAKE.CORTEX.EMBED_TEXT_768 is blocked),
-- and trial accounts need a payment method added before AI functions run (free credits still apply).
USE ROLE ACCOUNTADMIN; USE WAREHOUSE HR_WH; USE SCHEMA HR_ANALYTICS.ANALYTICS;

CREATE OR REPLACE TABLE HR_ANALYTICS.ANALYTICS.EXIT_COMMENT_EMBEDDINGS AS
SELECT COMMENT_ID, DEPARTMENT, JOB_ROLE, TENURE_BAND, PRIMARY_THEME, COMMENT_TEXT,
       AI_EMBED('snowflake-arctic-embed-m', COMMENT_TEXT) AS COMMENT_VEC
FROM HR_ANALYTICS.RAW.EXIT_COMMENTS;

-- Check: 300 rows, each with a 768-dimension vector
SELECT COUNT(*) FROM HR_ANALYTICS.ANALYTICS.EXIT_COMMENT_EMBEDDINGS WHERE COMMENT_VEC IS NOT NULL;
