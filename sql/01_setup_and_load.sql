-- 01: Setup and load (Evening 1)
-- Run in a Snowsight SQL worksheet as ACCOUNTADMIN on your trial account.

USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS HR_WH
  WAREHOUSE_SIZE = 'XSMALL' AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
USE WAREHOUSE HR_WH;

CREATE DATABASE IF NOT EXISTS HR_ANALYTICS;
CREATE SCHEMA IF NOT EXISTS HR_ANALYTICS.RAW;
CREATE SCHEMA IF NOT EXISTS HR_ANALYTICS.ANALYTICS;
USE SCHEMA HR_ANALYTICS.RAW;

-- Raw table for the public IBM HR Employee Attrition dataset (Kaggle, 35 columns, same order as the CSV)
CREATE OR REPLACE TABLE RAW.EMPLOYEES (
  AGE NUMBER, ATTRITION STRING, BUSINESS_TRAVEL STRING, DAILY_RATE NUMBER, DEPARTMENT STRING,
  DISTANCE_FROM_HOME NUMBER, EDUCATION NUMBER, EDUCATION_FIELD STRING, EMPLOYEE_COUNT NUMBER,
  EMPLOYEE_NUMBER NUMBER, ENVIRONMENT_SATISFACTION NUMBER, GENDER STRING, HOURLY_RATE NUMBER,
  JOB_INVOLVEMENT NUMBER, JOB_LEVEL NUMBER, JOB_ROLE STRING, JOB_SATISFACTION NUMBER,
  MARITAL_STATUS STRING, MONTHLY_INCOME NUMBER, MONTHLY_RATE NUMBER, NUM_COMPANIES_WORKED NUMBER,
  OVER_18 STRING, OVER_TIME STRING, PERCENT_SALARY_HIKE NUMBER, PERFORMANCE_RATING NUMBER,
  RELATIONSHIP_SATISFACTION NUMBER, STANDARD_HOURS NUMBER, STOCK_OPTION_LEVEL NUMBER,
  TOTAL_WORKING_YEARS NUMBER, TRAINING_TIMES_LAST_YEAR NUMBER, WORK_LIFE_BALANCE NUMBER,
  YEARS_AT_COMPANY NUMBER, YEARS_IN_CURRENT_ROLE NUMBER, YEARS_SINCE_LAST_PROMOTION NUMBER,
  YEARS_WITH_CURR_MANAGER NUMBER
);

-- Raw table for the synthetic exit-interview comments (exit_comments_synthetic.csv)
CREATE OR REPLACE TABLE RAW.EXIT_COMMENTS (
  COMMENT_ID STRING, DEPARTMENT STRING, JOB_ROLE STRING, TENURE_BAND STRING,
  PRIMARY_THEME STRING, COMMENT_TEXT STRING
);

-- Stage for uploads
CREATE OR REPLACE STAGE RAW.UPLOADS;
CREATE OR REPLACE FILE FORMAT RAW.CSV_FMT
  TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"';

-- NOW: in Snowsight go to Data > Databases > HR_ANALYTICS > RAW > Stages > UPLOADS,
-- click "+ Files", and upload both CSVs. Then run:

COPY INTO RAW.EMPLOYEES
  FROM @RAW.UPLOADS/WA_Fn-UseC_-HR-Employee-Attrition.csv
  FILE_FORMAT = (FORMAT_NAME = 'RAW.CSV_FMT');

COPY INTO RAW.EXIT_COMMENTS
  FROM @RAW.UPLOADS/exit_comments_synthetic.csv
  FILE_FORMAT = (FORMAT_NAME = 'RAW.CSV_FMT');

-- Check: expect 1470 employees and 300 comments
SELECT COUNT(*) FROM RAW.EMPLOYEES;
SELECT COUNT(*) FROM RAW.EXIT_COMMENTS;
